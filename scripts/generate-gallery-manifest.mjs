import { mkdirSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const rootDir = dirname(dirname(fileURLToPath(import.meta.url)));
const galleryDir = join(rootDir, "public", "gallery");
const outputFile = join(rootDir, "src", "features", "public", "data", "gallery.generated.ts");
const outputDir = dirname(outputFile);

const imageExtensions = new Set([".avif", ".gif", ".jpeg", ".jpg", ".png", ".webp"]);
const heightPattern = [432, 490, 697, 314, 697, 314, 432, 490, 490, 314, 697, 432];

const knownKinds = new Map([
  [1, "story"],
  [3, "video"],
  [5, "video"],
  [7, "story"],
  [11, "story"],
  [12, "video"],
  [13, "territory"],
  [14, "territory"],
  [15, "territory"],
  [16, "territory"],
  [17, "territory"],
]);

const knownAlts = new Map([
  [1, "Mujeres emprendedoras compartiendo"],
  [2, "Joyeria artesanal"],
  [3, "Feria de emprendimientos"],
  [4, "Proceso de tejido artesanal"],
  [5, "Arreglo floral artesanal"],
  [6, "Preparacion de alimentos"],
  [7, "Taller creativo"],
  [8, "Gastronomia artesanal"],
  [9, "Textiles de colores"],
  [10, "Maquina de coser"],
  [11, "Coleccion de moda"],
  [12, "Proceso de ceramica"],
  [13, "Atardecer sobre los Montes de Maria"],
  [14, "Iglesia rodeada de montanas y vegetacion"],
  [15, "Puesta de sol sobre montanas y flores"],
  [16, "Mirador natural con flores y montanas verdes"],
  [17, "Vista panoramica de un pueblo entre montanas"],
]);

function getExtension(fileName) {
  const index = fileName.lastIndexOf(".");
  return index === -1 ? "" : fileName.slice(index).toLowerCase();
}

function getGalleryNumber(fileName) {
  const match = fileName.match(/^gallery-(\d+)/i);
  return match ? Number(match[1]) : undefined;
}

function toDisplayName(fileName) {
  return fileName
    .replace(/\.[^.]+$/, "")
    .replace(/[-_]+/g, " ")
    .replace(/\s+/g, " ")
    .trim();
}

function getKind(fileName, galleryNumber) {
  if (galleryNumber && knownKinds.has(galleryNumber)) {
    return knownKinds.get(galleryNumber);
  }

  if (/territorio|territory/i.test(fileName)) {
    return "territory";
  }

  if (/video/i.test(fileName)) {
    return "video";
  }

  if (/historia|story/i.test(fileName)) {
    return "story";
  }

  return "photo";
}

const files = readdirSync(galleryDir)
  .filter((fileName) => imageExtensions.has(getExtension(fileName)))
  .filter((fileName) => fileName.toLowerCase() !== "gallery-hero.png")
  .sort((first, second) => {
    const firstNumber = getGalleryNumber(first);
    const secondNumber = getGalleryNumber(second);

    if (firstNumber && secondNumber) {
      return firstNumber - secondNumber;
    }

    return first.localeCompare(second, "es");
  });

const items = files.map((fileName, index) => {
  const galleryNumber = getGalleryNumber(fileName);
  const id = galleryNumber ?? index + 1;
  const alt = galleryNumber && knownAlts.has(galleryNumber) ? knownAlts.get(galleryNumber) : toDisplayName(fileName);

  return {
    id,
    image: `/gallery/${encodeURIComponent(fileName)}`,
    alt,
    kind: getKind(fileName, galleryNumber),
    height: heightPattern[index % heightPattern.length],
  };
});

const content = `// This file is generated by scripts/generate-gallery-manifest.mjs.
// Do not edit it manually. Add or remove images in public/gallery and run npm run gallery:generate.

export const galleryItems = ${JSON.stringify(items, null, 2)} as const;
`;

mkdirSync(outputDir, { recursive: true });
writeFileSync(outputFile, content);
console.log(`Generated ${items.length} gallery items in ${outputFile}`);
